"""写作提示词(中文,面向本地推理模型,要求结构化输出)。"""

from __future__ import annotations


def outline_prompt(topic: str, materials: str) -> str:
    return f"""你是中文头条图文作者。请为主题准备写作大纲。
主题:{topic}
参考材料:
{materials}
要求:输出 4-6 条中文大纲,每行一条,以 - 开头;不要输出解释。"""


def draft_prompt(topic: str, outline: str, materials: str, fewshot_text: str = "") -> str:
    fewshot_block = f"\n{fewshot_text}" if fewshot_text else ""
    return f"""你是中文头条图文作者。请根据主题与大纲写一篇 500-800 字的中文文章。
主题:{topic}
大纲:
{outline}
参考材料:
{materials}{fewshot_block}
要求:
1. 第一行是文章标题(不要加 # 号);
2. 正文分 3-5 段;
3. 引用参考材料时在句末标注 [编号];
4. 不得编造材料中没有的时间、数字、人物;无法确认处写"待核实";
5. 不得编造统计数字,即使标注为"预测/模拟/推演"也不允许;
6. 每条事实只依据**一篇**材料,不要把不同材料的时间/数字拼进同一句,并尽量沿用材料原句措辞;
7. 一个事实句子只装**一个**事实锚点:时间、数字、结果分开写(例:"决定于X日通过"与"自Y日起施行"写成两句),不要在一句里挤多个锚点,保持句子结构简单、贴近材料原句整句结构,便于引用逐字定位;
8. 严格按材料的时间口径写作:材料里写"将举办/预计/计划"的事件不得写成已发生;不要加入你对"当前现实时间"的论断或推测;
9. 参考文献、机构、数据只能来自参考材料:[编号] 只指向给定材料,不得编造"民政部/国家统计局/某高校研究"等材料里没有的来源,不得写"示例性文献/请以实际检索为准"之类的占位引用;
10. 标题必须能被正文直接支撑,不得用"集体倒戈/全面崩盘/所有人都在"等超出正文证据的强判断;
11. 建议、操作、清单类句子**不得写材料里没有的数字或区间**(如"提前 1—3 年""1 至 3 个月"):这类句子只写动作与条件,不写数字;
12. 引用官方文件名、政策表述和并列枚举(如"小步调整、弹性实施、分类推进")必须**逐字照抄**来源原句:不得增字、减字、换序,也不得补一个看起来合理的词;
13. 标题或正文承诺"两件核心大事/几个要点"这类数量时,正文必须把承诺的内容**逐条列出**(一是/二是…或编号列表);列不出来就不要这样写;
14. 直接输出文章,不要解释。"""


def claims_prompt(draft: str, article_numbers: list[int]) -> str:
    numbers = ",".join(str(n) for n in article_numbers) or "0"
    return f"""阅读下面文章,列出**每一句**关键事实陈述(带数字/日期/机构/人物的句子一条都不能漏,最多 12 条)。
文章:
{draft}
可用文章编号:{numbers}
要求:
1. claim 照抄文章里承载事实的那一句,不要改写、不要把几篇材料的数字/日期拼进同一句;
2. **一条 claim 只承载一个事实锚点**(一组数字、或一个日期、或一个人物/机构事件):文章里一句话含多个锚点时,拆成多条 claim,每条只保留自己那一个锚点及其直接上下文;
3. quote 从所引文章里**逐字复制、整句照抄**——从该句开头的标点(句首/逗号后)抄到句末标点,不得截半句、不得掐头去尾、不得省略中间;quote 必须包含这条 claim 的锚点;
4. quote 必须能在该文章里逐字找到,一个字都不能改;找不到就换一句能逐字找到的;若该文章承载不了这个锚点,换能承载它的文章编号;
5. 找不到任何逐字原文时 article_id 用 0、quote 留空。
只输出 JSON 数组,不要其他文字,格式:
[{{"claim":"文章原句","article_id":1,"quote":"来源原文逐字句"}}]"""


def review_prompt(draft: str, evidence_text: str) -> str:
    return f"""你是严格的中文内容评审。评审下面文章,只输出 JSON 对象,不要其他文字:
{{"score":0.0到1.0,"issues":["次要问题1","次要问题2"],"critical":["致命问题:事实错误/编造/无来源断言/内容截断"]}}
评分标准:事实与材料一致 40%,结构清晰 30%,标题吸引力 20%,无空话套话 10%。
存在事实错误、编造、无来源断言或内容截断时,必须写入 critical 数组;否则 critical 为空数组。
文章:
{draft}
证据链:
{evidence_text}"""


def revise_prompt(draft: str, issues: list[str]) -> str:
    issues_text = "\n".join(f"- {issue}" for issue in issues)
    return f"""请根据评审意见修改文章,保持原主题与事实边界,直接输出修改后的完整文章(第一行标题):
修改规则(违反任何一条即为失败):
1. 只改评审意见明确指出的问题,未被点名的段落逐字保留;
2. 不得新增原文没有的案例、地名、机构、人名、数字或"此处应改为"式说明;
3. 不得插入审稿说明、编辑备注、括号解释或对评审意见的复述;
4. 不得删除引用标注[编号],不得把来源改写成材料里没有的机构/文献;
5. 被点名的数字或区间若来源承载不了,按"删掉该数字、保留动作与条件"重写,不得换一个数字顶上;不得为了修补措辞而新增任何数字;
6. 引用官方表述与并列枚举必须逐字照抄来源原句,不得增字、减字、换序;
7. 直接输出修改后的完整文章,第一行仍是标题。
评审意见:
{issues_text}
原文:
{draft}"""


def detemplatize_prompt(draft: str, issues: list[str]) -> str:
    issues_text = "\n".join(f"- {issue}" for issue in issues)
    return f"""下面这篇文章的模板化读数超标,请做**定向重写**。
超标读数(每百句命中数):
{issues_text}
重写规则(违反任何一条即为失败):
1. 只处理上述读数涉及的句子:删除或改写公式化连接词/套话(如"首先/与此同时/综上所述"),改为具体表达或直接删除;拆分或替换"不仅…而且""从…到…"等并列模板句式;
2. 所有事实、数字、日期、人名、机构、引用标注[编号]必须逐字保留,不得改写、不得删除、不得新增;
3. 不得删减段落与句子数量(套话词本身除外),不得输出解释、说明或前后缀;
4. 直接输出重写后的完整文章,第一行仍是标题。
原文:
{draft}"""


def repair_sentence_prompt(
    draft: str, target: str, failure: str, missing: str, source_block: str, candidate_lines: list[str]
) -> str:
    candidates = "\n".join(candidate_lines) if candidate_lines else "(无其他候选来源)"
    return f"""下面这句话没有通过「事实-来源」核验,请**只重写这一句**。
问题句:
{target}
核验失败详情:
{failure}
缺失的锚点(数字/日期/人物/机构/因果):{missing}

这句话原本应绑定的来源原文(±1 句窗口,引用必须逐字来自这里):
{source_block}
材料池中确实包含缺失锚点的其他文章(如判定为"绑错文章",改用这里的原句):
{candidates}

重写规则(违反任何一条都会被判失败,改写后系统会用与门禁同一套规则复验):
1. 新句子的全部数字、日期、人物、机构必须逐字来自上面提供的某**一篇**来源(同一句只用一篇,不得拼接);
2. 一条句子只装一个事实锚点,尽量照抄来源原句措辞与时间口径(来源写"将/预计"不得写成已发生);
3. 来源承载不了这个事实时,删掉无法核验的具体内容或改述来源实际写过的话,绝不编造、换算、近似数字/日期;
4. 问题句里的数字或区间在来源里找不到时,删掉这个数字、只保留动作与条件就是正确修法,不得换一个数字或区间顶上;删掉数字后句子仍要留一个能逐字对上来源的锚点(机构/人物/日期/因果),不能改成没有事实的空话;
5. 新句子必须仍带至少一个事实锚点(数字/日期/人物/机构/因果),且该锚点逐字来自上述来源:不得改写成没有事实的空话;
6. 只输出重写后的那一个句子:不要引号、不要解释、不要句末标点、不要输出多句。

全文(仅提供上下文,其余句子不会被改动,也不要输出它们):
{draft}"""

